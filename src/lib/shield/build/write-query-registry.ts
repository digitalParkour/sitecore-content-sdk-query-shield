/**
 * GraphQL Query Registry
 *
 * Discovers all files named graphql.ts under src/, extracts exported GraphQL query strings,
 * normalizes them, hashes to an ID, and generates
 * graphql.shield.ts files plus client alias map for the Next.js client bundle.
 *
 * Invoked by runQueryShieldRegistry (e.g. from sitecore-tools project build).
 */

import crypto from "crypto";
import fs from "fs";
import path from "path";
import { normalizeQuery } from "../utils/graphql-util";

const SRC_DIR = path.resolve(process.cwd(), "src");
const GENERATED_DIR = path.resolve(process.cwd(), ".shield");

/** SHA-256 hex hash of normalized query (64 chars). */
function hashQuery(normalized: string): string {
  return crypto.createHash("sha256").update(normalized, "utf8").digest("hex");
}

/** True for `graphql.ts` or `*.graphql.ts`, excluding `*.graphql.shield.ts`. */
function isGraphqlModuleFileName(name: string): boolean {
  if (name === "graphql.ts") return true;
  if (name.endsWith(".graphql.ts") && !name.endsWith(".graphql.shield.ts"))
    return true;
  return false;
}

/** Discover all graphql.ts / *.graphql.ts files under src/. */
function discoverGraphqlFiles(): string[] {
  const files: string[] = [];
  function walk(dir: string) {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const e of entries) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else if (isGraphqlModuleFileName(e.name)) files.push(full);
    }
  }
  walk(SRC_DIR);
  return files;
}

/** Export name and resolved query string (from requiring the module). */
type ExportEntry = {
  name: string;
  query: string;
  normalized: string;
  id: string;
};

/** Load a graphql.ts module and return exported GraphQL query strings. */
function extractExportsFromModule(absolutePath: string): ExportEntry[] {
  const entries: ExportEntry[] = [];
  const relPath = path
    .relative(process.cwd(), absolutePath)
    .replace(/\\/g, "/");
  const fullPath = path.join(process.cwd(), relPath);

  try {
    // eslint-disable-next-line @typescript-eslint/no-require-imports -- dynamic load of app graphql modules; requires TS loader when run from sitecore-tools (tsx)
    const mod = require(fullPath);

    for (const [name, value] of Object.entries(mod)) {
      if (typeof value !== "string") continue;
      const trimmed = value.trim();
      if (
        !(
          trimmed.startsWith("query ") ||
          trimmed.startsWith("mutation ") ||
          trimmed.includes(" query ")
        )
      )
        continue;

      const normalized = normalizeQuery(value);
      const id = hashQuery(normalized);
      entries.push({ name, query: value, normalized, id });
    }
  } catch (err) {
    console.error(`Failed to load ${absolutePath}:`, err);
    throw err;
  }

  return entries;
}

/** Write graphql.shield.ts next to graphql.ts with export const Name = "hashId"; */
function writeGraphqlIdsFile(
  graphqlTsPath: string,
  entries: ExportEntry[],
): void {
  const rel = path.relative(process.cwd(), graphqlTsPath).replace(/\\/g, "/");
  const relNoExt = rel.replace(/\.ts$/, "");
  const idsPath = relNoExt.replace(/graphql$/, "graphql.shield") + ".ts";
  const lines = [
    // "/* eslint-disable prettier/prettier */",
    "// Auto-generated by src/lib/shield/build/write-query-registry.ts - do not edit.",
    ...entries.map((e) => `export const ${e.name} = "${e.id}";`),
    "",
  ];
  fs.mkdirSync(path.dirname(idsPath), { recursive: true });
  fs.writeFileSync(idsPath, lines.join("\n"), "utf8");
  console.log(`Wrote ${path.relative(process.cwd(), idsPath)}`);
}

/** Build alias map: relative path to graphql (no ext) -> relative path to graphql.shield.ts (for client bundle). Uses relative paths so the file is machine-independent. */
function buildAliasMap(
  fileToEntries: Map<string, ExportEntry[]>,
): Record<string, string> {
  const alias: Record<string, string> = {};
  for (const graphqlPath of fileToEntries.keys()) {
    const rel = path.relative(process.cwd(), graphqlPath).replace(/\\/g, "/");
    const relNoExt = rel.replace(/\.ts$/, "");
    const idsRel = relNoExt.replace(/graphql$/, "graphql.shield") + ".ts";
    alias[relNoExt] = idsRel;
  }
  return alias;
}

/** Write .shield/graphql-client-aliases.json for next.config (client-only resolve). */
function writeAliasModule(aliasMap: Record<string, string>): void {
  fs.mkdirSync(GENERATED_DIR, { recursive: true });
  const outPath = path.join(GENERATED_DIR, "graphql-client-aliases.json");
  fs.writeFileSync(outPath, JSON.stringify(aliasMap, null, 2), "utf8");
  console.log(`Wrote ${path.relative(process.cwd(), outPath)}`);
}

/** Optional: write query-registry.json for local fallback (ID -> query) if not using Edge Config. */
function writeRegistryJson(allItems: { key: string; value: string }[]): void {
  const obj: Record<string, string> = {};
  for (const { key, value } of allItems) obj[key] = value;
  const outPath = path.join(GENERATED_DIR, "query-registry.json");
  fs.writeFileSync(outPath, JSON.stringify(obj, null, 2), "utf8");
  console.log(
    `Wrote ${path.relative(process.cwd(), outPath)} (local fallback).`,
  );
}

/** Scans src/ for GraphQL modules and writes shield outputs. */
export function writeQueryRegistry(): void {
  const graphqlFiles = discoverGraphqlFiles();
  if (graphqlFiles.length === 0) {
    console.log("No graphql.ts files found under src/.");
    return;
  }
  console.log(
    `Found ${graphqlFiles.length} file(s): ${graphqlFiles
      .map((f) => path.relative(process.cwd(), f))
      .join(", ")}`,
  );

  const fileToEntries = new Map<string, ExportEntry[]>();
  const allItems: { key: string; value: string }[] = [];

  for (const filePath of graphqlFiles) {
    const relPath = path.relative(process.cwd(), filePath);
    const entries = extractExportsFromModule(filePath);
    if (entries.length === 0) {
      console.warn(`No GraphQL query exports found in ${relPath}, skipping.`);
      continue;
    }
    fileToEntries.set(path.resolve(process.cwd(), filePath), entries);
    for (const e of entries) {
      allItems.push({ key: e.id, value: e.normalized });
    }
    writeGraphqlIdsFile(path.resolve(process.cwd(), filePath), entries);
  }

  const aliasMap = buildAliasMap(fileToEntries);
  writeAliasModule(aliasMap);
  writeRegistryJson(allItems);
}
